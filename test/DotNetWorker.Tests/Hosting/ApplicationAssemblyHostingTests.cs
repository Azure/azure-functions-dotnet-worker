using System;
using System.Linq;
using System.Reflection;
using Microsoft.Azure.Functions.Worker.Builder;
using Microsoft.Azure.Functions.Worker.Core;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Xunit;

[assembly: WorkerExtensionStartupCodeExecutorInfo(typeof(Microsoft.Azure.Functions.Worker.Tests.Hosting.RecordingExtensionStartup))]

namespace Microsoft.Azure.Functions.Worker.Tests.Hosting;

public class ApplicationAssemblyHostingTests
{
    [Fact]
    public void InvokeAutoGeneratedConfigureMethods_ExplicitAssembly_RunsOnce()
    {
        var builder = new HostBuilder();

        builder.InvokeAutoGeneratedConfigureMethods(typeof(RecordingAutoConfigureStartup).Assembly);
        builder.InvokeAutoGeneratedConfigureMethods(typeof(RecordingAutoConfigureStartup).Assembly);

        Assert.Equal(1, builder.Properties[RecordingAutoConfigureStartup.InvocationCountKey]);
    }

    [Fact]
    public void InvokeAutoGeneratedConfigureMethods_ScopedAssembly_RunsTargetStartup()
    {
        var builder = new HostBuilder();

        using (WorkerApplicationAssemblyContext.Push(typeof(RecordingAutoConfigureStartup).Assembly))
        {
            builder.InvokeAutoGeneratedConfigureMethods();
        }

        Assert.Equal(1, builder.Properties[RecordingAutoConfigureStartup.InvocationCountKey]);
    }

    [Fact]
    public void InvokeAutoGeneratedConfigureMethods_DifferentAssembly_ThrowsBeforeSecondScan()
    {
        var builder = new HostBuilder();
        builder.InvokeAutoGeneratedConfigureMethods(typeof(RecordingAutoConfigureStartup).Assembly);

        Assert.Throws<InvalidOperationException>(() =>
            builder.InvokeAutoGeneratedConfigureMethods(typeof(string).Assembly));
        Assert.Equal(1, builder.Properties[RecordingAutoConfigureStartup.InvocationCountKey]);
    }

    [Fact]
    public void InvokeAutoGeneratedConfigureMethods_FailureIsCached()
    {
        var builder = new HostBuilder();
        builder.Properties[RecordingAutoConfigureStartup.ThrowKey] = true;

        InvalidOperationException first = Assert.Throws<InvalidOperationException>(() =>
            builder.InvokeAutoGeneratedConfigureMethods(typeof(RecordingAutoConfigureStartup).Assembly));
        builder.Properties[RecordingAutoConfigureStartup.ThrowKey] = false;
        InvalidOperationException second = Assert.Throws<InvalidOperationException>(() =>
            builder.InvokeAutoGeneratedConfigureMethods(typeof(RecordingAutoConfigureStartup).Assembly));

        Assert.Same(first, second);
        Assert.Equal(1, builder.Properties[RecordingAutoConfigureStartup.InvocationCountKey]);
    }

    [Fact]
    public void InvokeAutoGeneratedConfigureMethods_NullArguments_Throw()
    {
        var builder = new HostBuilder();

        Assert.Throws<ArgumentNullException>(() =>
            CoreWorkerHostBuilderExtensions.InvokeAutoGeneratedConfigureMethods(null, typeof(RecordingAutoConfigureStartup).Assembly));
        Assert.Throws<ArgumentNullException>(() => builder.InvokeAutoGeneratedConfigureMethods(null));
    }

    [Fact]
    public void AddFunctionsWorkerCore_ExplicitAssembly_IsIdempotent()
    {
        var services = new ServiceCollection();
        Assembly assembly = typeof(ApplicationAssemblyHostingTests).Assembly;

        IFunctionsWorkerApplicationBuilder first = services.AddFunctionsWorkerCore(assembly);
        IFunctionsWorkerApplicationBuilder second = services.AddFunctionsWorkerCore(assembly);

        Assert.Same(first, second);
        Assert.Single(services.Where(descriptor => descriptor.ServiceType == typeof(ExtensionStartupMarker)));
    }

    [Fact]
    public void FunctionsApplicationBuilder_ScopedAssembly_RunsGeneratedStartupOnce()
    {
        FunctionsApplicationBuilder builder;

        using (WorkerApplicationAssemblyContext.Push(typeof(ApplicationAssemblyHostingTests).Assembly))
        {
            builder = Microsoft.Azure.Functions.Worker.Builder.FunctionsApplication.CreateBuilder(Array.Empty<string>());
        }

        Assert.Single(builder.Services.Where(descriptor => descriptor.ServiceType == typeof(AutoConfigureStartupMarker)));
        Assert.Single(builder.Services.Where(descriptor => descriptor.ServiceType == typeof(ExtensionStartupMarker)));
    }

    [Fact]
    public void AddFunctionsWorkerCore_DifferentAssembly_ThrowsBeforeChangingServices()
    {
        var services = new ServiceCollection();
        services.AddFunctionsWorkerCore(typeof(ApplicationAssemblyHostingTests).Assembly);
        int registeredServiceCount = services.Count;

        Assert.Throws<InvalidOperationException>(() => services.AddFunctionsWorkerCore(typeof(string).Assembly));
        Assert.Equal(registeredServiceCount, services.Count);
    }

    [Fact]
    public void AddFunctionsWorkerCore_NullExplicitAssembly_Throws()
    {
        var services = new ServiceCollection();

        Assert.Throws<ArgumentNullException>(() => services.AddFunctionsWorkerCore(applicationAssembly: null));
    }
}

public sealed class RecordingAutoConfigureStartup : IAutoConfigureStartup
{
    internal const string InvocationCountKey = "RecordingAutoConfigureStartup.InvocationCount";
    internal const string ThrowKey = "RecordingAutoConfigureStartup.Throw";

    public void Configure(IHostBuilder hostBuilder)
    {
        int count = hostBuilder.Properties.TryGetValue(InvocationCountKey, out object value)
            ? (int)value
            : 0;
        hostBuilder.Properties[InvocationCountKey] = count + 1;
        hostBuilder.ConfigureServices(services => services.AddSingleton<AutoConfigureStartupMarker>());

        if (hostBuilder.Properties.TryGetValue(ThrowKey, out object shouldThrow) && (bool)shouldThrow)
        {
            throw new InvalidOperationException("Requested startup failure.");
        }
    }
}

public sealed class RecordingExtensionStartup : WorkerExtensionStartup
{
    public override void Configure(IFunctionsWorkerApplicationBuilder applicationBuilder)
    {
        applicationBuilder.Services.AddSingleton<ExtensionStartupMarker>();
    }
}

public sealed class AutoConfigureStartupMarker
{
}

public sealed class ExtensionStartupMarker
{
}
